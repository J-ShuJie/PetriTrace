    private static readonly Lazy<IReadOnlyDictionary<string, IReadOnlyDictionary<string, string>>> CatalogHolder =
        new(() => new Dictionary<string, IReadOnlyDictionary<string, string>>(StringComparer.OrdinalIgnoreCase)
        {
            [LocalizationService.Chinese] = Chinese!,
            [LocalizationService.English] = English!,
            [LocalizationService.German] = German!,
        });

    private static IReadOnlyDictionary<string, IReadOnlyDictionary<string, string>> Catalog => CatalogHolder.Value;

    public static IReadOnlyCollection<string> Keys => English.Keys.ToArray();

    public static string Get(string languageCode, string key)
    {
        if (Catalog.TryGetValue(languageCode, out var language) && language.TryGetValue(key, out var value))
            return value;
        return English.TryGetValue(key, out var fallback) ? fallback : key;
    }

